function syncPublishedArticles() {
  if (!window.CATEGORY_NEWS) return false;
  for (const story of window.LEAD_NEWS) {
    const group = window.CATEGORY_NEWS[story.navCategory];
    if (!group) continue;
    const row = [
      story.title.replace(/<br\s*\/?\s*>/gi, ' '),
      story.description.replace(/<br\s*\/?\s*>/gi, ' '),
      story.image,
      story.id
    ];
    const existing = group.articles.findIndex(item => item[3] === story.id);
    if (existing >= 0) group.articles[existing] = row;
    else group.articles.unshift(row);
  }
  window.ARCHIVE_ARTICLES = Object.entries(window.CATEGORY_NEWS).flatMap(([key, group]) =>
    group.articles.map(([title, description, image, id]) => ({
      id, navCategory: key, category: group.title, title, image,
      alt: group.title + ' 기사 연출 이미지', description,
      readingLabel: '교육뉴스', summary: description ? [description] : []
    }))
  );
  return true;
}

if (!syncPublishedArticles()) {
  document.addEventListener('DOMContentLoaded', syncPublishedArticles, { once: true });
}
