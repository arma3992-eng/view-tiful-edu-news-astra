  function applyCanvaImages() {
    const stories = new Map((window.ARCHIVE_ARTICLES || []).filter(s => s.canvaImage).map(s => [s.id, s]));
    const fallback = story => `assets/${story.image}.jpg`;
    const setImage = (img, story) => {
      if (!img || !story?.canvaImage || img.dataset.canvaApplied === '1') return;
      img.dataset.canvaApplied = '1';
      img.src = story.canvaImage;
      img.alt = story.alt || img.alt || '';
      img.addEventListener('error', () => { img.src = fallback(story); }, { once: true });
    };

    const currentId = new URLSearchParams(location.search).get('id');
    if (currentId && stories.has(currentId)) {
      setImage(document.querySelector('#article-image'), stories.get(currentId));
    }

    document.querySelectorAll('a[href*="article.html?id="]').forEach(link => {
      try {
        const href = new URL(link.href, location.href);
        const id = href.searchParams.get('id');
        const story = stories.get(id);
        if (!story) return;
        const img = link.querySelector('img') || link.closest('article')?.querySelector('img');
        setImage(img, story);
      } catch {}
    });
  }

  document.addEventListener('DOMContentLoaded', applyCanvaImages);
